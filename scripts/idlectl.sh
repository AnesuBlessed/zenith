#!/usr/bin/env bash
# =============================================================================
#  ZENITH — Idle Policy Helper (hypridle)
# =============================================================================
#  Protocol (consumed by services/IdleService.qml):
#    status                     -> MANAGED=true|false
#    apply <dim> <lock> <displayOff> <suspend> <hibernate> <dimPercent>
#    remove
#  All timeouts are seconds. A timeout of 0 disables that listener.
# =============================================================================
set -euo pipefail

cmd="${1:-}"
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
CONFIG="$CONFIG_HOME/hypr/hypridle.conf"
MARKER="# ZENITH-MANAGED-IDLE"

restart_idle() {
    pkill -x hypridle >/dev/null 2>&1 || true
    setsid hypridle >/dev/null 2>&1 &
}

require_uint() {
    if [[ ! "$2" =~ ^[0-9]+$ ]]; then
        echo "idlectl: invalid $1 '$2'" >&2
        exit 1
    fi
}

write_config() {
    local dim="$1" lock="$2" display="$3" suspend="$4" hibernate="$5" percent="$6"
    mkdir -p "$(dirname "$CONFIG")"
    {
        printf '%s\n' "$MARKER"
        printf '%s\n' "# Generated by Zenith — change values in Settings > Idle."
        printf '%s\n\n' "general {"
        # Go through lock.sh so the SDDM status snapshot is refreshed too.
        printf '  lock_cmd = %s\n' "$CONFIG_HOME/zenith/scripts/lock.sh"
        printf '  before_sleep_cmd = loginctl lock-session\n'
        printf '  after_sleep_cmd = hyprctl dispatch dpms on\n'
        printf '%s\n\n' "}"
        if (( dim > 0 )); then
            printf 'listener {\n  timeout = %s\n  on-timeout = brightnessctl -s set %s%%\n  on-resume = brightnessctl -r\n}\n\n' "$dim" "$percent"
        fi
        if (( lock > 0 )); then
            printf 'listener {\n  timeout = %s\n  on-timeout = loginctl lock-session\n}\n\n' "$lock"
        fi
        if (( display > 0 )); then
            printf 'listener {\n  timeout = %s\n  on-timeout = hyprctl dispatch dpms off\n  on-resume = hyprctl dispatch dpms on\n}\n\n' "$display"
        fi
        if (( suspend > 0 )); then
            printf 'listener {\n  timeout = %s\n  on-timeout = systemctl suspend\n}\n\n' "$suspend"
        fi
        if (( hibernate > 0 )); then
            printf 'listener {\n  timeout = %s\n  on-timeout = systemctl hibernate\n}\n' "$hibernate"
        fi
    } > "$CONFIG"
}

case "$cmd" in
    status)
        if [[ -f "$CONFIG" ]] && grep -qF "$MARKER" "$CONFIG"; then
            echo "MANAGED=true"
        else
            echo "MANAGED=false"
        fi
        ;;

    apply)
        dim="${2:-0}"; lock="${3:-0}"; display="${4:-0}"
        suspend="${5:-0}"; hibernate="${6:-0}"; percent="${7:-30}"
        require_uint dim "$dim"; require_uint lock "$lock"; require_uint display "$display"
        require_uint suspend "$suspend"; require_uint hibernate "$hibernate"
        require_uint percent "$percent"
        if (( percent < 5 || percent > 90 )); then percent=30; fi
        write_config "$dim" "$lock" "$display" "$suspend" "$hibernate" "$percent"
        echo "MANAGED=true"
        restart_idle
        ;;

    remove)
        if [[ -f "$CONFIG" ]] && grep -qF "$MARKER" "$CONFIG"; then
            cat > "$CONFIG" <<'DEFAULT'
# Zenith idle defaults — manual control restored.
general {
  lock_cmd = hyprlock
  before_sleep_cmd = loginctl lock-session
  after_sleep_cmd = hyprctl dispatch dpms on
}

listener {
  timeout = 300
  on-timeout = loginctl lock-session
}

listener {
  timeout = 330
  on-timeout = hyprctl dispatch dpms off
  on-resume   = hyprctl dispatch dpms on
}

listener {
  timeout = 1800
  on-timeout = systemctl suspend
}
DEFAULT
        fi
        echo "MANAGED=false"
        restart_idle
        ;;

    *)
        echo "Usage: idlectl.sh {status|apply|remove}" >&2
        exit 1
        ;;
esac