#!/usr/bin/env bash
# =============================================================================
#  ZENITH — Managed Shell Shortcuts (Hyprland Lua)
# =============================================================================
#  Protocol (consumed by services/ShortcutService.qml):
#    status [configPath]                  -> MANAGED=true|false
#    apply  [configPath] <9 booleans>     -> MANAGED=true
#    remove [configPath]                  -> MANAGED=false
#  Writes ~/.config/hypr/shortcuts.lua, which keybinds.lua loads with pcall.
# =============================================================================
set -euo pipefail

cmd="${1:-}"
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
HYPR_DIR="$CONFIG_HOME/hypr"
TARGET="$HYPR_DIR/shortcuts.lua"
MARKER="-- ZENITH-MANAGED-SHORTCUTS"

# Keep in sync with services/ShortcutService.qml entries order.
IDs=(launcher clipboard settings notifications wallpaper controlCenter lock regionScreenshot regionRecording)
Combos=("SUPER + A" "SUPER + V" "SUPER + comma" "SUPER + SHIFT + N" "SUPER + W" "SUPER + SPACE" "SUPER + ALT + L" "SUPER + SHIFT + S" "SUPER + SHIFT + R")
Commands=(
    'paths.quote(paths.root .. "/build/zenith-ctl") .. " toggle launcher"'
    'paths.quote(paths.root .. "/build/zenith-ctl") .. " toggle clipboard"'
    '"quickshell ipc call settings open"'
    '"quickshell ipc call notifications toggle"'
    'paths.quote(paths.root .. "/build/zenith-ctl") .. " toggle picker"'
    '"quickshell ipc call control-center toggle"'
    'paths.quote(paths.root .. "/scripts/lock.sh")'
    '"quickshell ipc call capture screenshot region copy"'
    '"quickshell ipc call capture record region"'
)

case "$cmd" in
    status)
        if [[ -f "$TARGET" ]] && grep -qF "$MARKER" "$TARGET"; then
            echo "MANAGED=true"
        else
            echo "MANAGED=false"
        fi
        ;;

    apply)
        shift || true
        # Optional config path argument (ShortcutService passes one, possibly empty).
        if [[ -z "${1:-}" || "${1}" == /* || "${1}" == *.lua || "${1}" == *.conf ]]; then
            shift || true
        fi
        values=("$@")
        mkdir -p "$HYPR_DIR"
        {
            printf '%s\n' "$MARKER"
            printf '%s\n' "-- Generated by Zenith — change bindings in Settings > Shortcuts."
            printf '%s\n' 'local paths = require("paths")'
            printf '%s\n\n' 'local function bind(combo, command)'
            printf '%s\n' '    pcall(hl.unbind, combo)'
            printf '%s\n' '    hl.bind(combo, hl.dsp.exec_cmd(command))'
            printf '%s\n\n' 'end'
            for index in "${!IDs[@]}"; do
                enabled="${values[$index]:-true}"
                if [[ "$enabled" == "true" ]]; then
                    printf 'bind("%s", %s)\n' "${Combos[$index]}" "${Commands[$index]}"
                fi
            done
        } > "$TARGET"
        echo "MANAGED=true"
        ;;

    remove)
        if [[ -f "$TARGET" ]] && grep -qF "$MARKER" "$TARGET"; then
            rm -f "$TARGET"
        fi
        echo "MANAGED=false"
        ;;

    *)
        echo "Usage: shortcutctl.sh {status|apply|remove} [configPath] [booleans...]" >&2
        exit 1
        ;;
esac